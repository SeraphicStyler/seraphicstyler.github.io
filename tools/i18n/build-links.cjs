/* Builds js/i18n/links.<code>.js from the two hand-edited link-page sources in
   this folder (links-i18n.js, then links-i18n-lp2.js; later wins per key).
   Edit the sources, then run:  node tools/i18n/build-links.cjs */
const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm');
const root = path.resolve(__dirname, '../..');
const context = { window: {} };
vm.createContext(context);
for (const f of ['links-i18n.js', 'links-i18n-lp2.js']) vm.runInContext(fs.readFileSync(path.join(__dirname, f), 'utf8'), context);
for (const [code, dict] of Object.entries(context.window.SS_TRANSLATIONS)) {
  fs.writeFileSync(path.join(root, 'js/i18n/links.' + code + '.js'),
    '/* Seraphic Styler — links page strings, ' + code + '. Generated by tools/i18n/build-links.cjs; edit the sources there. */\n' +
    'window.SS_KEYS_ADD(' + JSON.stringify(code) + ',' + JSON.stringify(dict) + ',true);\n');
}
console.log('wrote', Object.keys(context.window.SS_TRANSLATIONS).length, 'link-page language files');
